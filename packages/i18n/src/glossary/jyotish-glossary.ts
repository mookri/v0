/**
 * Translates a given Jyotish glossary key into the target locale.
 */
export function translateJyotishTerm(key: string, locale: JyotishLocale): string {
  const term = JYOTISH_GLOSSARY.find((t) => t.key === key);
  if (!term) {
    return key;
  }
  return term.translations[locale] ?? term.translations.en;
}

