// /lib/content/types.ts
// TypeScript interfaces for the Navdhya SEO content platform
// v2 — strict types, automation metadata, ad-network alignment

/** Valid content clusters for topic grouping */
export type ContentCluster =
  | 'brand'
  | 'pujas'
  | 'services'
  | 'ceremonies'
  | 'ritual-guides'
  | 'pandit-services'
  | 'festival-rituals'
  | 'spiritual-guides'
  | 'faq'
  | 'blog'
  | 'compare'
  | 'centers'
  | 'astrology'
  | 'vastu';

/** Valid JSON-LD schema types for structured data */
export type SchemaType =
  | 'Article'
  | 'FAQPage'
  | 'HowTo'
  | 'Service'
  | 'Organization'
  | 'LocalBusiness';

/** Valid search intents */
export type SearchIntent = 'informational' | 'transactional' | 'navigational';

/** Ad layout identifiers aligned with the ad-network component API */
export type AdLayout =
  | 'native_in_content'
  | 'inline_text'
  | 'medium_rectangle'
  | 'hero'
  | 'sticky_footer';

/** Ad placement identifiers */
export type AdPlacement =
  | 'article_inline_1'
  | 'article_inline_2'
  | 'sidebar_top'
  | 'sidebar_sticky'
  | 'hero_below_fold'
  | 'footer_rail';

/** FAQ entry used in FAQPage schema */
export interface FAQEntry {
  question: string;
  answer: string;
}

export type ComparisonTableRow = Record<string, string>;

export interface ServiceProcessStep {
  step: string;
  description: string;
}

export interface ServicePackage {
  name: string;
  description: string;
  price: string;
  duration?: string;
}

export interface ServiceDetails {
  summary?: string;
  priceRange?: string;
  image?: string;
  galleryImages?: string[];
  packages?: ServicePackage[];
  highlights?: string[];
  benefits?: string[];
  process?: ServiceProcessStep[];
  includes?: string[];
  serviceProof?: string[];
  bookingLeadTime?: string;
  serviceAreas?: string[];
}

/** HowTo step used in HowTo schema */
export interface HowToStep {
  name: string;
  text: string;
  /** Optional image for this step */
  imageUrl?: string;
}

/** Native ad configuration — fully typed against the ad-network engine */
export interface NativeAd {
  enabled: boolean;
  placement: AdPlacement;
  layout: AdLayout;
  title: string;
  description: string;
  ctaText: string;
  ctaUrl: string;
  imageUrl?: string;
  /** Minimum quality score 0–100; engine will skip ad if below threshold */
  minQualityScore?: number;
}

/**
 * Automation metadata injected at build time.
 * Used for ISR scheduling, cache busting, and content health checks.
 */
export interface AutomationMeta {
  /** Build fingerprint — SHA-256 of content used for cache invalidation */
  contentHash: string;
  /** ISO timestamp when content was generated by the automation pipeline */
  generatedAt: string;
  /** Pipeline version that generated this content */
  pipelineVersion: string;
  /** Whether this page should trigger a re-index ping on revalidation */
  pingIndexNow?: boolean;
  /** Custom ISR revalidation interval in seconds (overrides default 3600) */
  revalidateAfter?: number;
}

/**
 * Open Graph / social sharing overrides.
 * Falls back to title/description/heroImage if absent.
 */
export interface OGOverrides {
  ogTitle?: string;
  ogDescription?: string;
  ogImageUrl?: string;
  twitterCard?: 'summary' | 'summary_large_image';
}

/**
 * Core content page interface — every JSON content file must conform to this shape.
 */
export interface SEOPage {
  /** Unique page identifier, e.g. "nav-brand-001" */
  id: string;

  /** URL slug, e.g. "what-is-navdhya" */
  slug: string;

  /** Topic cluster for grouping and internal linking */
  cluster: ContentCluster;

  /** Display title (H1) */
  title: string;

  /** Meta title for <title> tag */
  metaTitle: string;

  /** Meta description */
  metaDescription: string;

  /** Primary target keyword */
  primaryKeyword: string;

  /** Secondary/supporting keywords */
  secondaryKeywords: string[];

  /** Hyperlocal, transliterated, and supporting keyword variants */
  keywordVariants?: string[];

  /** Search intent classification */
  searchIntent: SearchIntent;

  /** JSON-LD schema type to generate */
  schemaType: SchemaType;

  /** Full article content (HTML string) */
  content: string;

  /** H2 section headings (page outline) */
  outline: string[];

  /** Slugs of related pages for internal linking */
  relatedSlugs: string[];

  /** ISO date of last update */
  lastUpdated: string;

  /** Optional editorial review date */
  lastReviewed?: string;

  /** Author name */
  author: string;

  /** Optional reviewer or subject-matter expert */
  reviewedBy?: string;

  /** Estimated reading time in minutes */
  readingTime: number;

  /** Optional FAQ entries for FAQPage schema */
  faqs?: FAQEntry[];

  /** Optional HowTo steps for HowTo schema */
  howToSteps?: HowToStep[];

  /** Optional excerpt / short summary for listings and previews */
  excerpt?: string;

  /** Optional hero image URL */
  heroImage?: string;

  /** Optional proof points used for trust and summary modules */
  proofPoints?: string[];

  /** Optional comparison rows for competitor and pricing pages */
  comparisonTable?: ComparisonTableRow[];

  /** Optional service-page specific structured details */
  serviceDetails?: ServiceDetails;

  /** Optional editorial pricing note shown in content and schema */
  pricingNote?: string;

  /** Optional Delhi NCR angle or locality framing */
  localAngle?: string;

  /** Optional cities or subregions the page explicitly targets */
  targetCities?: string[];

  /** Optional internal links that must appear on the page */
  requiredInternalLinks?: string[];

  /** Optional anchor texts editors should prefer when linking in */
  recommendedAnchorTexts?: string[];

  /**
   * Optional native ad slot 1 — mid-article placement.
   * @deprecated Use adSlots array instead for multi-slot control.
   */
  adSlot1?: NativeAd;

  /**
   * Optional native ad slot 2 — lower-article placement.
   * @deprecated Use adSlots array instead for multi-slot control.
   */
  adSlot2?: NativeAd;

  /**
   * Structured ad slot declarations.
   * Supersedes adSlot1/adSlot2. Engine picks best fill for each placement.
   */
  adSlots?: NativeAd[];

  /** Open Graph / Twitter Card overrides */
  og?: OGOverrides;

  /** Automation pipeline metadata — injected at build time, never manually edited */
  automation?: AutomationMeta;

  /** Canonical URL override — defaults to /{basePath}/{slug} */
  canonicalUrl?: string;

  /** Noindex flag — set to true to exclude from Google (draft pages, etc.) */
  noindex?: boolean;
}

/**
 * Registry entry mapping a slug to its content file and cluster.
 */
export interface RegistryEntry {
  file: string;
  cluster: ContentCluster;
}

/**
 * Cluster metadata in the registry.
 */
export interface ClusterMeta {
  label: string;
  basePath: string;
}

/**
 * Full registry shape loaded from registry.json.
 */
export interface ContentRegistry {
  pages: Record<string, RegistryEntry>;
  clusters: Record<ContentCluster, ClusterMeta>;
}

/**
 * Result of a page content validation run.
 */
export interface ValidationResult {
  slug: string;
  pass: boolean;
  errors: string[];
  warnings: string[];
  score: number; // 0–100
}
